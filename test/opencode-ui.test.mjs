import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm, mkdir } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { SettingsStore } from '../opencode/store.mjs';
import { createSettingsServer } from '../opencode/settings-server.mjs';

test('reference settings UI saves tool selection, shortcut, overlay and browser preferences', {skip:process.env.OPENCODE_UI_TEST!=='1',timeout:60000}, async t=>{
  const { chromium }=await import('playwright');
  const home=await mkdtemp(path.join(os.tmpdir(),'opencode-cu-ui-')),store=new SettingsStore(home);
  let locale='zh';
  const server=await createSettingsServer({store,onChange:()=>{},onLocale:next=>{locale=next;},getStatus:()=>({active:false,locale})});
  const browser=await chromium.launch({channel:'msedge',headless:true});
  t.after(async()=>{await browser.close();await server.close();await rm(home,{recursive:true,force:true});});
  const context=await browser.newContext({locale:'zh-CN',viewport:{width:1280,height:1000}}), page=await context.newPage(), errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(server.url);
  await page.locator('[data-wincu-settings]').waitFor();
  assert.equal(await page.locator('[data-wincu-tool]').count(),26);
  await page.locator('label').filter({has:page.locator('#opencode-cu-toolPreset-lazy')}).click();
  await page.getByRole('button',{name:'保存更改',exact:true}).click();
  await page.getByText('已保存',{exact:true}).waitFor();assert.equal((await store.snapshot()).value.toolPreset,'lazy');
  await page.locator('#opencode-cu-browserApp').selectOption('firefox');
  await page.getByRole('button',{name:'保存更改',exact:true}).click();
  await page.getByText('已保存',{exact:true}).waitFor();assert.equal((await store.snapshot()).value.browserVisible,false);
  await page.getByRole('button',{name:'录制快捷键',exact:true}).click();await page.keyboard.press('Control+Alt+k');
  await page.getByRole('button',{name:'保存更改',exact:true}).click();
  await page.getByText('已保存',{exact:true}).waitFor();assert.equal((await store.snapshot()).value.stopShortcut,'Ctrl+Alt+K');
  const progress=page.locator('[data-wincu-progress-details]');await progress.locator('summary').click();
  await page.locator('#opencode-cu-progressOverlayWidth').fill('480');
  await page.getByRole('button',{name:'保存更改',exact:true}).click();
  await page.getByText('已保存',{exact:true}).waitFor();assert.equal((await store.snapshot()).value.progressOverlayWidth,480);
  await page.reload();await page.locator('[data-wincu-settings]').waitFor();
  assert.equal(await page.locator('#opencode-cu-toolPreset-lazy').isChecked(),true);
  assert.match(await page.locator('[data-wincu-shortcut]').innerText(),/Ctrl/);
  await page.getByRole('button',{name:'English',exact:true}).click();
  await page.getByRole('button',{name:'中文',exact:true}).waitFor();assert.equal(locale,'en');
  await page.getByRole('button',{name:'中文',exact:true}).click();
  await page.getByRole('button',{name:'English',exact:true}).waitFor();assert.equal(locale,'zh');
  const artifacts=path.resolve('.work/validation');await mkdir(artifacts,{recursive:true});
  await page.screenshot({path:path.join(artifacts,'settings-desktop.png'),fullPage:true});
  await page.setViewportSize({width:480,height:900});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:path.join(artifacts,'settings-mobile.png'),fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('Settings UI: 26 tools, lazy mode, browser visibility, shortcut recording, overlay size, reload and narrow layout passed');
});
